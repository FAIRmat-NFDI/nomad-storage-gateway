func TestPresignedURL_UnconfiguredPublicEndpoint(t *testing.T) {
	// Create router with unconfigured PublicEndpoint
	cfg := config.Config{}
	router, err := NewRouter(cfg, nil)
	if err != nil {
		t.Fatalf("NewRouter() error = %v", err)
	}

	// Request to /zip/abcdef without publicEndpoint configured should return 500 Internal Server Error
	req := httptest.NewRequest(http.MethodGet, "/zip/abcdef?X-Amz-Algorithm=AWS4-HMAC-SHA256", nil)
	rec := httptest.NewRecorder()
	router.ServeHTTP(rec, req)

	if rec.Code != http.StatusInternalServerError {
		t.Fatalf("status = %d, want %d; body = %q", rec.Code, http.StatusInternalServerError, rec.Body.String())
	}
	if !strings.Contains(rec.Body.String(), "public endpoint not configured") {
		t.Fatalf("expected error message to mention public endpoint, got %q", rec.Body.String())
	}
}
