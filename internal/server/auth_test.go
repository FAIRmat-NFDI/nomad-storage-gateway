func TestPresignedURL_TamperingRejections(t *testing.T) {
	cfg := testConfig()
	router, err := NewRouter(cfg, testFilerSuccess())
	if err != nil {
		t.Fatalf("NewRouter() error = %v", err)
	}

	tests := []struct {
		name    string
		signOpt signOptions
		reqPath string
		want    int
	}{
		{
			name: "tampered signature",
			signOpt: signOptions{
				rawQueryMutator: func(q url.Values) {
					sig := q.Get("X-Amz-Signature")
					if len(sig) > 4 {
						q.Set("X-Amz-Signature", "0000"+sig[4:])
					}
				},
			},
			reqPath: "/zip/abcdef",
			want:    http.StatusForbidden,
		},
		{
			name: "wrong secret key",
			signOpt: signOptions{
				secretKey: "wrong-secret-key",
			},
			reqPath: "/zip/abcdef",
			want:    http.StatusForbidden,
		},
		{
			name: "wrong access key in credential",
			signOpt: signOptions{
				accessKey: "wrong-access-key",
			},
			reqPath: "/zip/abcdef",
			want:    http.StatusForbidden,
		},
		{
			name: "tampered expiration parameter",
			signOpt: signOptions{
				rawQueryMutator: func(q url.Values) {
					q.Set("X-Amz-Expires", "3600")
				},
			},
			reqPath: "/zip/abcdef",
			want:    http.StatusForbidden,
		},
		{
			name: "injected unauthorized query parameter",
			signOpt: signOptions{
				rawQueryMutator: func(q url.Values) {
					q.Set("injected_param", "attack")
				},
			},
			reqPath: "/zip/abcdef",
			want:    http.StatusForbidden,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			req := buildSignedRequest(t, cfg, http.MethodGet, tt.reqPath, tt.signOpt)
			rec := httptest.NewRecorder()
			router.ServeHTTP(rec, req)

			if rec.Code != tt.want {
				t.Fatalf("status = %d, want %d; body = %q", rec.Code, tt.want, rec.Body.String())
			}
		})
	}
}

