type signOptions struct {
	accessKey       string
	secretKey       string
	region          string
	signingTime     time.Time
	expires         time.Duration
	rawQueryMutator func(url.Values)
}

func buildSignedRequest(t *testing.T, cfg config.Config, method, requestPath string, opts signOptions) *http.Request {
	t.Helper()

	accessKey := opts.accessKey
	if accessKey == "" {
		accessKey = cfg.SeaweedFS.S3AccessKey
	}
	secretKey := opts.secretKey
	if secretKey == "" {
		secretKey = cfg.SeaweedFS.S3SecretKey
	}
	region := opts.region
	if region == "" {
		region = "us-east-1"
	}
	signingTime := opts.signingTime
	if signingTime.IsZero() {
		signingTime = time.Now().UTC()
	}
	expires := opts.expires
	if expires == 0 {
		expires = 15 * time.Minute
	}

	publicURL, err := url.Parse(cfg.SeaweedFS.PublicEndpoint)
	if err != nil {
		t.Fatalf("parse public endpoint: %v", err)
	}

	u := *publicURL
	u.Path = strings.TrimSuffix(publicURL.Path, "/") + requestPath
	q := u.Query()
	q.Set("X-Amz-Expires", strconv.FormatInt(int64(expires.Seconds()), 10))
	u.RawQuery = q.Encode()

	req, err := http.NewRequest(method, u.String(), nil)
	if err != nil {
		t.Fatalf("new request: %v", err)
	}

	signer := v4.NewSigner(func(o *v4.SignerOptions) {
		o.DisableURIPathEscaping = true
	})

	signedURI, _, err := signer.PresignHTTP(
		context.Background(),
		aws.Credentials{
			AccessKeyID:     accessKey,
			SecretAccessKey: secretKey,
		},
		req,
		"UNSIGNED-PAYLOAD",
		"s3",
		region,
		signingTime,
	)
	if err != nil {
		t.Fatalf("presign request: %v", err)
	}

	signedURL, err := url.Parse(signedURI)
	if err != nil {
		t.Fatalf("parse signed URI: %v", err)
	}

	query := signedURL.Query()
	if opts.rawQueryMutator != nil {
		opts.rawQueryMutator(query)
	}

	return httptest.NewRequest(method, requestPath+"?"+query.Encode(), nil)
}

