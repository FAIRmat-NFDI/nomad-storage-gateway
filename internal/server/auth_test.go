func TestPresignedURL_ExpirationAndClockSkew(t *testing.T) {
	cfg := testConfig()
	router, err := NewRouter(cfg, testFilerSuccess())
	if err != nil {
		t.Fatalf("NewRouter() error = %v", err)
	}

	now := time.Now().UTC()

	tests := []struct {
		name    string
		signOpt signOptions
		want    int
	}{
		{
			name: "expired URL",
			signOpt: signOptions{
				signingTime: now.Add(-2 * time.Hour),
				expires:     30 * time.Minute,
			},
			want: http.StatusForbidden,
		},
		{
			name: "future dated beyond skew tolerance",
			signOpt: signOptions{
				signingTime: now.Add(2 * time.Hour),
				expires:     15 * time.Minute,
			},
			want: http.StatusForbidden,
		},
		{
			name: "future dated within clock skew tolerance",
			signOpt: signOptions{
				signingTime: now.Add(5 * time.Minute),
				expires:     15 * time.Minute,
			},
			want: http.StatusTemporaryRedirect,
		},
		{
			name: "invalid negative expiration",
			signOpt: signOptions{
				rawQueryMutator: func(q url.Values) {
					q.Set("X-Amz-Expires", "-10")
				},
			},
			want: http.StatusBadRequest,
		},
		{
			name: "invalid zero expiration",
			signOpt: signOptions{
				rawQueryMutator: func(q url.Values) {
					q.Set("X-Amz-Expires", "0")
				},
			},
			want: http.StatusBadRequest,
		},
		{
			name: "expiration exceeding 7 days",
			signOpt: signOptions{
				rawQueryMutator: func(q url.Values) {
					q.Set("X-Amz-Expires", "604801")
				},
			},
			want: http.StatusBadRequest,
		},
		{
			name: "non-numeric expiration",
			signOpt: signOptions{
				rawQueryMutator: func(q url.Values) {
					q.Set("X-Amz-Expires", "not-a-number")
				},
			},
			want: http.StatusBadRequest,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			req := buildSignedRequest(t, cfg, http.MethodGet, "/zip/abcdef", tt.signOpt)
			rec := httptest.NewRecorder()
			router.ServeHTTP(rec, req)

			if rec.Code != tt.want {
				t.Fatalf("status = %d, want %d; body = %q", rec.Code, tt.want, rec.Body.String())
			}
		})
	}
}

