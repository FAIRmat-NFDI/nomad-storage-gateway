func TestPresignedURL_Boto3CannedVector(t *testing.T) {
	// Precomputed test vector generated by Python's botocore.auth.S3SigV4QueryAuth
	// (matching NOMAD's StorageRedirects.presign_url):
	//
	// URL: https://nomad-lab.eu/files/zip/abcdef
	// Credentials: key="seaweed-access", secret="seaweed-secret", region="us-east-1"
	// Signing Time: 2026-09-02T16:40:06Z
	// Expires: 900s
	// Generated Signature: 5143c401c13ea76327d0fe339e7c0b020d7f8d2d251e5d63aa05a71138a4a478

	cannedDate := time.Date(2026, 9, 2, 16, 40, 6, 0, time.UTC)
	mockNow := cannedDate.Add(30 * time.Second) // 30s after signing

	cfg := testConfig()
	router, err := newRouter(cfg, testFilerSuccess(), func() time.Time { return mockNow })
	if err != nil {
		t.Fatalf("newRouter() error = %v", err)
	}

	cannedQuery := url.Values{
		"X-Amz-Algorithm":     {"AWS4-HMAC-SHA256"},
		"X-Amz-Credential":    {"seaweed-access/20260902/us-east-1/s3/aws4_request"},
		"X-Amz-Date":          {"20260902T164006Z"},
		"X-Amz-Expires":       {"900"},
		"X-Amz-SignedHeaders": {"host"},
		"X-Amz-Signature":     {"5143c401c13ea76327d0fe339e7c0b020d7f8d2d251e5d63aa05a71138a4a478"},
	}

	req := httptest.NewRequest(http.MethodGet, "/zip/abcdef?"+cannedQuery.Encode(), nil)
	rec := httptest.NewRecorder()
	router.ServeHTTP(rec, req)

	if rec.Code != http.StatusTemporaryRedirect {
		t.Fatalf("status = %d, want %d; body = %q", rec.Code, http.StatusTemporaryRedirect, rec.Body.String())
	}
}

